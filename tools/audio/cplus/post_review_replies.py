def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--pr", type=int, required=True)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    comments = json.loads(
        gh("api", f"repos/{args.repo}/pulls/{args.pr}/comments", "--paginate")
    )
    open_ids = {c["id"] for c in comments}
    missing = sorted(set(REPLIES) - open_ids)
    if missing:
        print(f"WARNING: {len(missing)} known thread(s) are not open any more: {missing}")

    posted = 0
    for thread_id, body in sorted(REPLIES.items()):
        if thread_id not in open_ids:
            print(f"skip {thread_id}: thread not open")
            continue
        if args.dry_run:
            print(f"would reply to {thread_id}")
            continue
        result = subprocess.run(
            ["gh", "api", "-X", "POST", f"repos/{args.repo}/pulls/{args.pr}/comments",
             "-f", f"body={body}", "-F", f"in_reply_to={thread_id}"],
            capture_output=True, text=True,
        )
        if result.returncode != 0:
            print(f"FAIL {thread_id}: {result.stderr.strip()[:200]}")
            continue
        posted += 1
        print(f"replied to {thread_id}")
    print(f"posted {posted} replies")


if __name__ == "__main__":
    main()
