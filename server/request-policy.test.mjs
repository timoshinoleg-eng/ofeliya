import assert from 'node:assert/strict';
import { proxyHops, clientIp, corsHeaders } from './request-policy.mjs';
assert.equal(proxyHops('0'), 0);
assert.equal(proxyHops(undefined), 0);
assert.equal(proxyHops('2'), 2);
for (const invalid of ['-1', 'foo', '2junk', '17']) assert.throws(() => proxyHops(invalid));
const req = (ip, forwarded) => ({ socket: { remoteAddress: ip }, headers: { 'x-forwarded-for': forwarded } });
assert.equal(clientIp(req('192.0.2.2', '203.0.113.1'), 0, ['192.0.2.2']), '192.0.2.2');
assert.equal(clientIp(req('192.0.2.2', '203.0.113.1'), 1, ['127.0.0.1']), '192.0.2.2');
assert.equal(clientIp(req('::ffff:127.0.0.1', '198.51.100.9, 203.0.113.1'), 1, ['127.0.0.1']), '203.0.113.1');
assert.equal(clientIp(req('127.0.0.1', 'fake, 203.0.113.1'), 1, ['127.0.0.1']), '127.0.0.1');
assert.equal(clientIp(req('127.0.0.1', '203.0.113.1'), 2, ['127.0.0.1']), '127.0.0.1');
const request = origin => ({ headers: { host: 'game.example', origin } });
assert.equal(corsHeaders(request('https://game.example'))['Access-Control-Allow-Origin'], 'https://game.example');
assert.equal(corsHeaders(request('https://evil.example'))['Access-Control-Allow-Origin'], undefined);
assert.equal(corsHeaders(request('null'))['Access-Control-Allow-Origin'], undefined);
assert.equal(corsHeaders(request('https://frontend.example'), ['https://frontend.example'])['Access-Control-Allow-Origin'], 'https://frontend.example');
assert.equal(corsHeaders(request(undefined)).Vary, 'Origin');
console.log('Request policy: PASS (zero hops, trusted peers, spoofed chains, origin allowlist)');
