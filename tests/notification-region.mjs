import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const module = { exports: {} };
new Function('module', 'exports', ts.transpileModule(readFileSync('src/ui/NotificationRegion.ts', 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } }).outputText)(module, module.exports);
const { NotificationRegion } = module.exports;
const region = new NotificationRegion(), shown = [], destroyed = [], visibility = [], done = {};
const notice = key => finish => { shown.push(key); done[key] = finish; return { setVisible: v => visibility.push([key, v]), destroy: () => destroyed.push(key) }; };
region.enqueue('startup', notice('startup'));
region.enqueue('achievement', notice('achievement'));
region.enqueue('immune', notice('immune'));
region.enqueue('achievement', notice('duplicate'));
assert.deepEqual(shown, ['startup']);
assert.equal(region.occupied, true);
region.setBlocked(true);
done.startup();
assert.deepEqual(shown, ['startup'], 'blocked region cannot drain pending notifications');
region.setBlocked(false);
assert.deepEqual(shown, ['startup', 'achievement']);
done.startup();
assert.deepEqual(shown, ['startup', 'achievement'], 'stale completion cannot release current owner');
done.achievement();
assert.deepEqual(shown, ['startup', 'achievement', 'immune']);
done.immune();
assert.equal(region.occupied, false);
assert.deepEqual(destroyed, ['startup', 'achievement', 'immune']);
region.enqueue('achievement', notice('duplicate'));
assert.equal(region.occupied, false, 'same logical notification appears once per run');
const b = new NotificationRegion();
b.setBlocked(true);
b.enqueue('pending', notice('pending'));
b.destroy();
b.setBlocked(false);
assert.ok(!shown.includes('pending'), 'terminal result drops run-local queued surfaces');
const c = new NotificationRegion();
c.enqueue('active', notice('active'));
c.enqueue('queued', notice('queued'));
c.destroy();
done.active();
assert.ok(!shown.includes('queued'), 'late callbacks cannot revive queue after result');
const e = new NotificationRegion();
e.enqueue('instant', finish => { finish(); return { setVisible() { }, destroy() { destroyed.push('instant'); } }; });
assert.equal(e.occupied, false);
assert.equal(destroyed.filter(x => x === 'instant').length, 1);

const batch=new NotificationRegion(), batchShown=[];
const surface=()=>({setVisible(){},destroy(){}});
batch.enqueue('stage-old',()=>{batchShown.push('stage-old');return surface()});
batch.enqueue('pending-old',()=>{batchShown.push('pending-old');return surface()});
batch.cancel(['stage-old','pending-old']);
assert.deepEqual(batchShown,['stage-old'],'stage reset cancels stale batch atomically without presenting cancelled successors');
const shutdown=new NotificationRegion();let disposed=false;
shutdown.enqueue('closed-scene',()=>({setVisible(){},destroy(){disposed=true}}));
shutdown.destroy(false);
assert.equal(disposed,false,'Phaser shutdown owns object cleanup after scene plugins close');

console.log('notification FIFO, duplicate/stale callback, suspend/resume, terminal cleanup: PASS');
